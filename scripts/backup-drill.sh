#!/usr/bin/env bash
# Backup + restore rehearsal for booking-v2 (Phase 0: "ยังไม่เคยทดสอบ restore").
#
# Copies the data of one database into a scratch database that has the same schema, then proves the
# copy is complete. A backup nobody has restored is not a backup.
#
#   BOOKING_DB_URL=postgres://…/postgres  DRILL_DB_URL=postgres://…/booking_restore  scripts/backup-drill.sh
#
# Target rules (the script refuses anything else):
#   * a different database from the source — never the same host+name
#   * a scratch database, not the production one
#   * it already has the schema: roles anon/authenticated/service_role and the auth schema.
#     On a plain Postgres run supabase/tests/supabase-shim.sql first; on a Supabase scratch project
#     they exist. The script only drops and rebuilds schema "public".
#
# What it does: pg_dump --data-only (public + auth.users) → rebuild the target's public schema from
# supabase/migrations → restore → scripts/verify-restore.js compares every table, RLS flag and policy.
set -euo pipefail

source_url="${BOOKING_DB_URL:?set BOOKING_DB_URL to the database to back up}"
target_url="${DRILL_DB_URL:?set DRILL_DB_URL to an empty scratch database with the same schema}"
keep="${DRILL_KEEP:-0}"

here="$(cd "$(dirname "$0")/.." && pwd)"
work="$(mktemp -d)"
cleanup() { [ "$keep" = "1" ] || rm -rf "$work"; }
trap cleanup EXIT

host_of() { printf '%s' "$1" | sed -E 's#^[a-z]+://([^@/]*@)?([^:/]+).*#\2#'; }
db_of() { local d="${1##*/}"; printf '%s' "${d%%\?*}"; }

if [ "$(host_of "$source_url")" = "$(host_of "$target_url")" ] && [ "$(db_of "$source_url")" = "$(db_of "$target_url")" ]; then
  echo "refusing to drill into the source database itself" >&2
  exit 1
fi

psql "$target_url" -v ON_ERROR_STOP=1 -q -c "select 1" >/dev/null
if [ "$(psql "$target_url" -At -c "select 1 from pg_roles where rolname = 'service_role'")" != "1" ]; then
  echo "target has no Supabase roles — run supabase/tests/supabase-shim.sql on it first" >&2
  exit 1
fi
if [ "$(psql "$target_url" -At -c "select 1 from pg_namespace where nspname = 'auth'")" != "1" ]; then
  echo "target has no auth schema — run supabase/tests/supabase-shim.sql on it first" >&2
  exit 1
fi

# A newer client than the server (e.g. pg_dump 17/18 against Postgres 16) writes
# `SET transaction_timeout = 0;`, a GUC the server does not know — the restore would stop on line 1
# with "unrecognized configuration parameter". Drop that one line; everything else stays as dumped.
strip_newer_settings() { sed -i '/^SET transaction_timeout = 0;$/d' "$1"; }

echo "== 1/4 dump  data of $(db_of "$source_url") on $(host_of "$source_url")"
pg_dump "$source_url" --data-only --schema=public --no-owner --no-privileges --file="$work/public.sql"
strip_newer_settings "$work/public.sql"
if [ "$(psql "$source_url" -At -c "select 1 from pg_tables where schemaname = 'auth' and tablename = 'users'")" = "1" ]; then
  pg_dump "$source_url" --data-only --table=auth.users --no-owner --no-privileges --file="$work/users.sql"
  strip_newer_settings "$work/users.sql"
fi

echo "== 2/4 rebuild schema of $(db_of "$target_url") from supabase/migrations"
psql "$target_url" -v ON_ERROR_STOP=1 -q -c 'drop schema public cascade' -c 'create schema public'
for f in "$here"/supabase/migrations/*.sql; do
  psql "$target_url" -v ON_ERROR_STOP=1 -q -f "$f"
done

# booking_activity.id is GENERATED ALWAYS; a data-only dump restores the ids, so identity must accept
# explicit values while loading and go back to ALWAYS afterwards (pg_dump puts that in its pre-data
# section, which --data-only leaves out).
psql "$target_url" -v ON_ERROR_STOP=1 -q <<'SQL'
do $$
declare r record;
begin
  for r in select table_name, column_name from information_schema.columns
            where table_schema = 'public' and is_identity = 'YES'
  loop
    execute format('alter table public.%I alter column %I set generated by default', r.table_name, r.column_name);
  end loop;
end $$;
SQL

echo "== 3/4 restore into $(db_of "$target_url")"
# auth.users first: public rows (business_members.user_id, platform_admins.user_id) point at it.
if [ -f "$work/users.sql" ]; then
  psql "$target_url" -v ON_ERROR_STOP=1 -q -c 'truncate table auth.users cascade'
  psql "$target_url" -v ON_ERROR_STOP=1 -q -f "$work/users.sql"
fi
psql "$target_url" -v ON_ERROR_STOP=1 -q -f "$work/public.sql"

psql "$target_url" -v ON_ERROR_STOP=1 -q <<'SQL'
do $$
declare r record;
begin
  for r in select table_name, column_name from information_schema.columns
            where table_schema = 'public' and is_identity = 'YES'
  loop
    execute format('alter table public.%I alter column %I set generated always', r.table_name, r.column_name);
  end loop;
end $$;
SQL

echo "== 4/4 verify"
node "$here/scripts/verify-restore.js" "$source_url" "$target_url"

echo
echo "drill passed. The dump itself is $(du -h "$work/public.sql" | cut -f1) of SQL."
if [ "$keep" = "1" ]; then
  echo "kept the dump in $work (DRILL_KEEP=1)"
fi
exit 0
